            alf <- alf[chromosome %in% c(1:22,'X','Y')]
            alf <- alf[nd > 30 & nd*n>5 & nd*(1-n)>5][td > 30 & td*t>5 & td*(1-t)>5]
            
            
            # tumor table
            alf[,allele_ratio:=t]
            alf[,depth:=td]
            alf[,maf:=abs(allele_ratio-.5)+.5]
            
            # normal table
            alf_n <- copy(alf)
            alf_n[,allele_ratio:=n]
            alf_n[,depth:=nd]
            alf_n[,maf:=abs(allele_ratio-.5)+.5]
        }
