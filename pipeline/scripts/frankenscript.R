    matching_t <- str_detect(opts$tumor_cnr,names)
    
    if (sum(matching_t)==1) {
        tix <- which(matching_t)
    } else if (sum(n)==1) {
        tix <- which(n!=T)
    } else if (sum(cfdna)==1) {
        tix <- which(cfdna)
    } else if (sum(t)==1) {
        tix <- which(t)
