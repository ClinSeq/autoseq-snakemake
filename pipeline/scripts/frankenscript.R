                                 show.legend = F,
                                 fill='white',
                                 col='blue',
                                 nudge_y = labels[chromosome==chr]$nudge,
                                 size=2.2,
                                 box.padding = .1,
                                 label.padding = .1,
                                 point.padding = .1,
                                 # Width of the line segments.
                                 segment.size = 0.5,
                                 segment.color = 'blue')
        }
        
    }
    # last few items
    p$pos_alleleratio <- p$pos_alleleratio +
        scale_x_continuous(breaks = seq(0,max(targets[chromosome==chr]$end+10e6),10e6),
                           #minor_breaks = seq(0,max(targets[chromosome==chr]$end+10e6),1e6),
                           expand = c(.01,.01),
                           limits = c(0,max(targets[chromosome==chr]$end+10e6)),
                           labels = c(0,paste0(seq(10,max(targets[chromosome==chr]$end/1e6)+10,10),'M'))) +
        scale_y_continuous(breaks = c(0,.2,.4,.6,.8,1),
                           minor_breaks = c(.1,.3,.5,.7,.9),
                           limits = 0:1) +
        theme(panel.grid.major.x = element_line(),
              panel.grid.minor.y = element_line(),
              #panel.grid.minor.x = element_line(color = 'lightgrey'),
              axis.line = element_line(),
              axis.ticks = element_line(),
              plot.margin = margin(6, 6, 6, 6, "pt"))
    
    ## by order ---------------------------------------------------------
    
    ### logR ---------------------------------------------------------
    
    # logR by order
    p$order_log2 <- ggplot(targets[chromosome==chr]) + xlab(paste('Chromosome',chr,'order')) + ylab('Corrected depth') +
        geom_point(data=cancergenes_here[chromosome==chr], #  <<--- this is a dummy for colors to work out.
                   mapping = aes(x=bin,y=1,fill=`selected genes`),shape=1,col='#FFFFFF',size=.1,show.legend = F) +
        # geom_segment(data=targets[chromosome==chr & gene=='Background'],col='darkgrey',size=1,
        #              mapping = aes(x=start,xend=end,y=2^log2,yend=2^log2)) +
        geom_point(data=targets[chromosome==chr & is.na(`selected genes`)],
                   mapping = aes(x=bin,y=2^log2),fill='#606060',col='#202020',shape=21,size=1,alpha=alpha) +
        geom_point(data=targets[chromosome==chr & !is.na(`selected genes`)],
                   mapping = aes(x=bin,y=2^log2,fill=`selected genes`),shape=21,col='#00000050',size=1,show.legend = F) +
        geom_point(data=targets[chromosome==chr & !is.na(`selected genes`) & type=='exonic'],
                   mapping = aes(x=bin,y=2^log2,fill=`selected genes`),shape=23,col='#000000FF',size=1,show.legend = F) +
        geom_segment(data=segments[chromosome==chr],col='green',size=.6,
                     mapping = aes(x=start,xend=end,y=2^log2,yend=2^log2)) +
        geom_point(data=segments[chromosome==chr],col='green',size=.4,shape=18,
                   mapping = aes(x=start,y=2^log2)) +
        geom_point(data=segments[chromosome==chr],col='green',size=.4,shape=18,
                   mapping = aes(x=end,y=2^log2)) +
        scale_fill_hue(l=70) + 
        scale_y_log10(limits=ylims, breaks=ybreaks, minor_breaks=yminorbreaks) +
        scale_x_continuous(expand = c(.01,.01),
                           limits = c(min(targets[chromosome==chr]$bin),
                                      max(targets[chromosome==chr]$bin))) +
        theme(panel.grid.major.x = element_line(),
              panel.grid.minor.y = element_line(),
              panel.grid.minor.x = element_line(),
              axis.line = element_blank(),
              axis.ticks = element_blank(),
              plot.margin = margin(6, 6, 6, 6, "pt"))
    # add cancer gene labels to the above
    if (any(cancergenes_here$chromosome==chr)) p$order_log2 <- p$order_log2 +
        geom_label_repel(data = cancergenes_here[chromosome==chr],
                         mapping = aes(x=(startbin+endbin)/2,y=2^mean,label=label,fill=`selected genes`),
                         nudge_y=cancergenes_here[chromosome==chr]$nudge,
                         angle=0,size=1.8,show.legend = F,parse=T,
                         segment.color = '#50505090',
                         box.padding = .1,
                         label.padding = .15,
                         point.padding = .1,
                         # Add extra padding around each data point.
                         #point.padding = unit(1.6, 'lines'),
                         # Width of the line segments.
                         segment.size = 0.5,
                         # Draw an arrow from the label to the data point.
                         arrow = arrow(length = unit(0.01, 'npc')))
    
    ### alleleratio ---------------------------------------------------------
    
    # allele ratio by order
    p$order_alleleratio <- ggplot(snps[chromosome==chr]) + xlab(paste('Chromosome',chr,' order')) + ylab('Allele ratio') +
        geom_point(data=cancergenes_here[chromosome==chr], #  <<--- this is a dummy for colors to work out.
                   mapping = aes(x=bin,y=.5,fill=`selected genes`),shape=1,col='#FFFFFF',size=.1,show.legend = F) +
        geom_point(data=snps[chromosome==chr & is.na(`selected genes`)],mapping = aes(x=bin,y=allele_ratio),fill='#606060',col='#202020',shape=21,size=1,alpha=alpha) +
        geom_point(data=snps[chromosome==chr & !is.na(`selected genes`)],mapping = aes(x=bin,y=allele_ratio,fill=`selected genes`),shape=21,col='#00000050',size=1,show.legend = F) +
        scale_fill_hue(l=70)
    # somatic mutations
    if (!is.null(somatic)) if (nrow(somatic[chromosome==chr])>0) {
        p$order_alleleratio <- p$order_alleleratio +
            geom_point(data=somatic[chromosome==chr],mapping = aes(x=bin,y=AF.T,shape=`point mutation`,col=`point mutation`),fill='red',size=1.2,show.legend = F) +
            scale_shape_manual(values = c('snv'=21,'ins'=25,'del'=24,'other'=22)) +
            scale_color_manual(values = c('snv'='darkred','ins'='red','del'='red','other'='darkred'))
        
        labels <- somatic[chromosome==chr & SYMBOL %in% cancergenes$gene & CANONICAL=='YES' & IMPACT %in% c('MODERATE','HIGH')]
        if (nrow(labels)>0) {
            labels[,ppos:=str_extract(Protein_position,'[0-9]*')]
            labels[,aa:=str_extract(Amino_acids,'[A-Z]$')][is.na(aa),aa:='']
            labels[Consequence=='stop_gained',aa:='*']
            labels[str_detect(Consequence,'frameshift'),aa:='fs']
            labels[str_detect(Consequence,'inframe'),aa:='if']
            labels[str_detect(Consequence,'splice'),aa:='sp']
            labels[,label:=paste0(SYMBOL,':',ppos,aa)]
            labels[,nudge:=.1][AF.T>.8,nudge:= -.1]
            
            p$order_alleleratio <- p$order_alleleratio +
                geom_label_repel(data = labels[chromosome==chr],mapping = aes(x=bin,y=AF.T,label=label),
                                 show.legend = F,
                                 fill='white',
                                 col='darkred',
                                 nudge_y = labels$nudge,
                                 size=2.2,
                                 box.padding = .1,
                                 label.padding = .1,
                                 point.padding = .1,
                                 # Width of the line segments.
                                 segment.size = 0.5,
                                 segment.color = 'red')
        }
    }
    # germline mutations
    if (!is.null(germline)) if (nrow(germline[chromosome==chr])>0) {
        p$order_alleleratio <- p$order_alleleratio +
            geom_point(data=germline,mapping = aes(x=bin,y=allele_ratio,shape=`point mutation`),col='grey',fill='blue',size=1.2,show.legend = F) +
            scale_shape_manual(values = c('snv'=21,'ins'=25,'del'=24,'other'=22))
        
        labels <- germline[SYMBOL %in% cancergenes$gene & CANONICAL=='YES' & IMPACT %in% c('MODERATE','HIGH')]
        if (nrow(labels[chromosome==chr])>0) {
            labels[,ppos:=str_extract(Protein_position,'[0-9]*')]
            labels[,aa:=str_extract(Amino_acids,'[A-Z]$')][is.na(aa),aa:='']
            labels[Consequence=='stop_gained',aa:='*']
            labels[str_detect(Consequence,'frameshift'),aa:='fs']
            labels[str_detect(Consequence,'inframe'),aa:='if']
            labels[str_detect(Consequence,'splice'),aa:='sp']
            labels[,label:=paste0(SYMBOL,':',ppos,aa)]
            labels[,nudge:=.1][allele_ratio>.8,nudge:= -.1]
            
            p$order_alleleratio <- p$order_alleleratio +
                geom_label_repel(data = labels[chromosome==chr],mapping = aes(x=bin,y=allele_ratio,label=label),
                                 show.legend = F,
                                 fill='white',
                                 col='blue',
                                 nudge_y = labels[chromosome==chr]$nudge,
                                 size=2.2,
                                 box.padding = .1,
                                 label.padding = .1,
                                 point.padding = .1,
                                 # Width of the line segments.
                                 segment.size = 0.5,
                                 segment.color = 'blue')
        }
        
    }
    # last few items
    p$order_alleleratio <- p$order_alleleratio +
        scale_x_continuous(expand = c(.01,.01),
                           limits = c(min(targets[chromosome==chr]$bin),
                                      max(targets[chromosome==chr]$bin))) +
        scale_y_continuous(breaks = c(0,.2,.4,.6,.8,1),
                           minor_breaks = c(.1,.3,.5,.7,.9),
                           limits = 0:1) +
        theme(panel.grid.major.x = element_line(),
              panel.grid.minor.y = element_line(),
              panel.grid.minor.x = element_line(),
              axis.line = element_blank(),
              axis.ticks = element_blank(),
              plot.margin = margin(6, 6, 6, 6, "pt"))
    
    
    
    ## finalize ---------------------------------------------------------
    
    for (i in 1:length(p)) p[[i]] <- p[[i]] +
        guides(fill=guide_legend(override.aes=list(shape=21,size=2))) +
        guides(shape=guide_legend(override.aes=list(size=2)))
    
    pa <- plot_annotation(
        title = paste(basename(name),'       Chromosome',chr),
    )
    
    if (!wgs) {
        layout <-  "AABB
                    AABB
                CCCC
                DDDD
                EEEE
                FFFF"
        fig <-
            p$gc_log2+
            p$scatter+
            p$order_log2+
            p$order_alleleratio+
            p$pos_log2+
            p$pos_alleleratio+
            plot_layout(design = layout,guides = 'collect')
    } else {
        layout <-  "AABB
                CCCC
                DDDD"
        fig <-
            p$gc_log2+
            p$scatter+
            p$pos_log2+
            p$pos_alleleratio+
            plot_layout(design = layout,guides = 'collect')
    }
    
    print(fig+pa)
    
    
}



