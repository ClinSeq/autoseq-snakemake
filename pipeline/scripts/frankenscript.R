    date <- format(Sys.time(), "%a %b %e %Y, %H:%M")
    
    pa <- plot_annotation(
        title = paste(basename(name),'  ',date,'  ',stats),
        caption = paste0('Frankenplot version ', scriptversion, ' on ',date, '.\nMarkus Mayrhofer and Johan Lindberg, Karolinska Institutet')
    )
    
    if (!wgs) { # Targeted:
        layout <-  "AABBBBBB
                CCDDDDDD
                EEFFFFFF
                GGGGGGGG
                HHHHHHHH
                IIJJJJJJ
                IIJJJJJJ"
        fig <-
            p$gc_rawdepth+p$order_rawdepth+
            p$gc_log2+p$order_log2+
            p$depth_alleleratio+p$order_alleleratio+
            p$pos_log2+
            p$pos_alleleratio+
            p$nogrid+p$grid+
