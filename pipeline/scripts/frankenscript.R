                                 show.legend = F,
                                 fill='white',
                                 col='darkred',
                                 nudge_y = labels$nudge,
                                 size=2.2,
                                 box.padding = .1,
                                 label.padding = .1,
                                 point.padding = .1,
                                 # Width of the line segments.
                                 segment.size = 0.5,
                                 segment.color = 'red')
        }
    }
    # germline mutations
    if (!is.null(germline)) if (nrow(germline[chromosome==chr])>0) {
        p$pos_alleleratio <- p$pos_alleleratio +
            geom_point(data=germline,mapping = aes(x=start,y=allele_ratio,shape=`point mutation`),col='grey',fill='blue',size=1.2,show.legend = F) +
