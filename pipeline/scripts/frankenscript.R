              axis.ticks = element_line())
    
    ### alleleratio-logR ---------------------------------------------------------
    
    # allele ratio vs depth/log2
    p$depth_alleleratio <- ggplot(targets) + xlab('Corrected depth') + ylab('Allele ratio') +
